pub(super) async fn create_telemetry_tables(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    create_table(
        manager,
        "events",
        vec![
            string("id").primary_key().to_owned(),
            string("application_id"),
            string("environment_id"),
            string("name"),
            bigint("timestamp"),
            string("day"),
            nullable_string("anonymous_id"),
            nullable_string("session_id"),
            nullable_string("app_version"),
            nullable_string("launcher_version"),
            nullable_string("os"),
            text("attributes"),
            nullable_string("dedupe_key"),
            bigint("received_at"),
        ],
    )
    .await?;
    create_table(
        manager,
        "metric_points",
        vec![
            string("id").primary_key().to_owned(),
            string("application_id"),
            string("environment_id"),
            string("name"),
            string("metric_type"),
            double("value"),
            nullable_string("unit"),
            bigint("timestamp"),
            text("attributes"),
            bigint("received_at"),
        ],
    )
    .await?;
    create_table(
        manager,
        "logs",
        vec![
            string("id").primary_key().to_owned(),
            string("application_id"),
            string("environment_id"),
            string("level"),
            text("message"),
            nullable_string("logger"),
            nullable_string("trace_id"),
            nullable_string("span_id"),
            bigint("timestamp"),
            text("attributes"),
            bigint("received_at"),
        ],
    )
    .await?;
    create_table(
        manager,
        "daily_aggregates",
        vec![
            string("id").primary_key().to_owned(),
            string("application_id"),
            string("environment_id"),
            string("day"),
            string("kind"),
            string("dimension"),
            string("dimension_value"),
            bigint("count"),
            nullable_double("sum"),
            bigint("updated_at"),
        ],
    )
    .await?;
    create_index(
        manager,
        "idx_events_scope_time",
        "events",
        &["application_id", "environment_id", "timestamp"],
        false,
    )
    .await?;
    create_index(
        manager,
        "idx_events_day_user",
        "events",
        &["application_id", "day", "anonymous_id"],
        false,
    )
    .await?;
    create_index(manager, "uq_events_dedupe", "events", &["dedupe_key"], true).await?;
    create_index(
        manager,
        "idx_metrics_scope_time",
        "metric_points",
        &["application_id", "environment_id", "timestamp"],
        false,
    )
    .await?;
    create_index(
        manager,
        "idx_logs_scope_time",
        "logs",
        &["application_id", "environment_id", "timestamp"],
        false,
    )
    .await
}

