use sea_orm_migration::prelude::*;

use super::columns::{
    bigint, boolean, create_index, create_table, double, integer, nullable_bigint, nullable_double,
    nullable_string, nullable_text, string, text,
};

pub(super) async fn create_identity_tables(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    create_table(
        manager,
        "system_state",
        vec![string("key").primary_key().to_owned(), text("value")],
    )
    .await?;
    create_table(
        manager,
        "users",
        vec![
            string("id").primary_key().to_owned(),
            string("email").unique_key().to_owned(),
            string("username"),
            text("password_hash"),
            string("locale"),
            boolean("active"),
            bigint("created_at"),
        ],
    )
    .await?;
    create_table(
        manager,
        "roles",
        vec![
            string("id").primary_key().to_owned(),
            string("name").unique_key().to_owned(),
            boolean("builtin"),
            text("permissions"),
            bigint("created_at"),
        ],
    )
    .await?;
    create_table(
        manager,
        "sessions",
        vec![
            string("id").primary_key().to_owned(),
            string("user_id"),
            string("token_hash").unique_key().to_owned(),
            string("csrf_token"),
            bigint("expires_at"),
            bigint("created_at"),
        ],
    )
    .await?;
    create_table(
        manager,
        "role_bindings",
        vec![
            string("id").primary_key().to_owned(),
            string("user_id"),
            string("role_id"),
            nullable_string("application_id"),
            bigint("created_at"),
        ],
    )
    .await
}

