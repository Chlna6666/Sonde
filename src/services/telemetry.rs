#[derive(Clone, Copy, Debug)]
pub struct IngestTokenContext<'a> {
    pub client_ip: &'a str,
    pub user_agent: &'a str,
    pub raw_key: Option<&'a str>,
}

#[derive(Clone, Copy, Debug)]
pub struct IngestRequestContext<'a> {
    pub client_ip: &'a str,
    pub user_agent: &'a str,
    pub credential: Option<&'a str>,
    pub signature: Option<&'a str>,
    pub timestamp: Option<&'a str>,
    pub nonce: Option<&'a str>,
    pub method: &'a str,
    pub path: &'a str,
}

#[derive(Clone, Debug)]
pub struct IngestScope {
    pub application_id: String,
    pub environment_id: String,
    source_ip: String,
    device_id: String,
    risk_tier: RiskTier,
}

impl IngestScope {
    fn storage_scope(&self) -> TelemetryScope {
        TelemetryScope {
            application_id: self.application_id.clone(),
            environment_id: self.environment_id.clone(),
        }
    }

    pub(crate) fn signed_device_id(&self) -> &str {
        &self.device_id
    }
}

#[derive(Debug, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IngestTokenRequest {
    /// Stable pseudonymous identifier generated by the client for the current device.
    /// Historical activity/session/version/OS state is derived from telemetry by the platform.
    pub device_id: String,
}

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct IngestTokenResponse {
    pub token: String,
    pub token_type: &'static str,
    pub expires_in: i64,
    pub expires_at: i64,
    pub signing_key: String,
    pub signature_version: &'static str,
    pub scopes: Vec<String>,
}

pub fn has_permission(scopes: &[String], required_perm: &str) -> bool {
    scopes.iter().any(|scope| {
        scope == "*"
            || scope == "ingest"
            || scope == "telemetry.ingest"
            || scope == required_perm
            || (required_perm == "telemetry.events"
                && (scope == "events" || scope == "ingest.events"))
            || (required_perm == "telemetry.metrics"
                && (scope == "metrics" || scope == "ingest.metrics"))
            || (required_perm == "telemetry.logs" && (scope == "logs" || scope == "ingest.logs"))
            || (required_perm == "telemetry.errors"
                && (scope == "errors" || scope == "ingest.errors"))
            || (required_perm == "telemetry.heartbeat"
                && (scope == "heartbeat" || scope == "ingest.heartbeat"))
    })
}

pub fn match_user_agent(rule: &str, user_agent: &str) -> bool {
    let rule = rule.trim();
    if rule.is_empty() || rule == "*" {
        return true;
    }
    if user_agent.is_empty() {
        return false;
    }
    for part in rule.split(',') {
        let pattern = part.trim();
        if pattern.is_empty() {
            continue;
        }
        if let Some(prefix) = pattern.strip_suffix('*') {
            if user_agent.starts_with(prefix) {
                return true;
            }
        } else if user_agent == pattern || user_agent.contains(pattern) {
            return true;
        }
    }
    false
}

/// Exchange a long-lived bootstrap API key for a short-lived device-bound ingest token.
pub async fn issue_token(
    installed: &InstalledState,
    request: IngestTokenContext<'_>,
    body: IngestTokenRequest,
) -> Result<IngestTokenResponse, AppError> {
    let user_agent = validate_user_agent(request.user_agent)?;
    let pepper = installed.auth_security.pepper();

    if !ingest_bootstrap::charge_ip_token(&installed.database, pepper, request.client_ip).await? {
        return Err(AppError::TooManyRequests);
    }

    let device_id = validate_device_id(&body.device_id)?.to_owned();
    let raw_key = request.raw_key.ok_or(AppError::Unauthorized)?;
    let hash = hex::encode(Sha256::digest(raw_key.as_bytes()));
    let context = ingest_auth::api_key_context(
        &installed.database,
        &hash,
        chrono::Utc::now().timestamp_millis(),
    )
    .await?
    .ok_or(AppError::Unauthorized)?;

    if !ingest_bootstrap::check_device_enrollment(
        &installed.database,
        pepper,
        request.client_ip,
        &context.application_id,
        &device_id,
    )
    .await?
    {
        return Err(AppError::TooManyRequests);
    }

    let device_hash = device_identity::scoped_hash_parts(
        &context.application_id,
        &context.environment_id,
        &device_id,
    );
    let risk_score = device_risk::risk_score_for_device(
        &installed.database,
        &context.application_id,
        &context.environment_id,
        &device_hash,
    )
    .await?
    .unwrap_or(0);
    let policy = ingest_abuse::policy_for_score(risk_score);
    if !charge_device_token_budget(
        installed,
        &context.application_id,
        &device_id,
        policy.token_cost_multiplier,
    )
    .await?
    {
        return Err(AppError::TooManyRequests);
    }

    let client_binding = installed
        .auth_security
        .ingest
        .client_binding(user_agent, pepper)?;
    let claim_scopes = ingest_abuse::claims_scopes(&context.scopes, policy.tier);
    let (token, signing_key, expires_at) = installed.auth_security.ingest.issue_ingest_token(
        &context.application_id,
        &context.environment_id,
        &device_id,
        &client_binding,
        &claim_scopes,
        policy.token_ttl_seconds,
        pepper,
    )?;

    Ok(IngestTokenResponse {
        token,
        token_type: "Bearer",
        expires_in: policy.token_ttl_seconds,
        expires_at,
        signing_key,
        signature_version: ingest_signature::SIGNATURE_VERSION,
        scopes: context.scopes,
    })
}

pub async fn scope_from_context_with_permission(
    installed: &InstalledState,
    request: IngestRequestContext<'_>,
    required_perm: &str,
    raw_body: &[u8],
) -> Result<IngestScope, AppError> {
    let user_agent = validate_user_agent(request.user_agent)?;

    if !installed
        .auth_security
        .ingest
        .check_ip_ingest_rate(request.client_ip)
        .await
        || !installed
            .auth_security
            .ingest
            .check_ip_ingest_bytes(request.client_ip, raw_body.len())
            .await
    {
        return Err(AppError::TooManyRequests);
    }

    let auth_header = request.credential.ok_or(AppError::Unauthorized)?;
    if !auth_header.starts_with("sndt_") {
        return Err(AppError::IngestTokenRequired);
    }
    signed_scope(
        installed,
        request,
        required_perm,
        raw_body,
        auth_header,
        user_agent,
    )
    .await
}

async fn signed_scope(
    installed: &InstalledState,
    request: IngestRequestContext<'_>,
    required_perm: &str,
    raw_body: &[u8],
    token: &str,
    user_agent: &str,
) -> Result<IngestScope, AppError> {
    let claims = installed
        .auth_security
        .ingest
        .verify_ingest_token(token, installed.auth_security.pepper())
        .ok_or(AppError::Unauthorized)?;
    let policy = ingest_abuse::policy_for_claims(&claims.scopes);

    let expected_binding = installed
        .auth_security
        .ingest
        .client_binding(user_agent, installed.auth_security.pepper())?;
    if claims.client_binding != expected_binding || !has_permission(&claims.scopes, required_perm) {
        return Err(AppError::Forbidden);
    }

    let signature = request.signature.ok_or(AppError::Forbidden)?;
    let timestamp = request
        .timestamp
        .ok_or(AppError::Forbidden)?
        .parse::<i64>()
        .map_err(|_| AppError::Validation("invalid x-sonde-timestamp".into()))?;
    let nonce = request.nonce.ok_or(AppError::Forbidden)?;
    if nonce.len() < 8
        || nonce.len() > 128
        || nonce
            .chars()
            .any(|character| character.is_control() || character.is_whitespace())
    {
        return Err(AppError::Validation(
            "x-sonde-nonce must be 8..128 visible non-whitespace bytes".into(),
        ));
    }

    let signing_key = installed
        .auth_security
        .ingest
        .signing_key_for_claims(&claims, installed.auth_security.pepper())?;
    ingest_signature::verify(ingest_signature::VerifyRequest {
        signing_key: &signing_key,
        timestamp_ms: timestamp,
        nonce,
        method: request.method,
        path: request.path,
        body: raw_body,
        signature_hex: signature,
    })?;

    if !ingest_nonce::record_once(
        &installed.database,
        &claims.token_id,
        nonce,
        claims.expires_at,
    )
    .await?
    {
        let device_hash = device_identity::scoped_hash_parts(
            &claims.application_id,
            &claims.environment_id,
            &claims.device_id,
        );
        let now = chrono::Utc::now().timestamp_millis();
        if let Err(error) = device_risk::record_replay_detected(
            &installed.database,
            &claims.application_id,
            &claims.environment_id,
            &device_hash,
            now,
        )
        .await
        {
            warn!(
                error = %error,
                application_id = %claims.application_id,
                environment_id = %claims.environment_id,
                "failed to record verified ingest replay risk signal"
            );
        }
        warn!(
            application_id = %claims.application_id,
            environment_id = %claims.environment_id,
            source_ip = %request.client_ip,
            device_hash = %device_hash,
            "replayed signed ingest request rejected"
        );
        return Err(AppError::Forbidden);
    }

    if !charge_device_request_budget(
        installed,
        &claims.application_id,
        &claims.device_id,
        policy.request_cost_multiplier,
    )
    .await
        || !installed
            .auth_security
            .ingest
            .check_device_ingest_bytes(
                &claims.application_id,
                &claims.device_id,
                ingest_abuse::scaled_cost(raw_body.len(), policy.byte_cost_multiplier),
            )
            .await
    {
        return Err(AppError::TooManyRequests);
    }

    Ok(IngestScope {
        application_id: claims.application_id,
        environment_id: claims.environment_id,
        source_ip: request.client_ip.to_owned(),
        device_id: claims.device_id,
        risk_tier: policy.tier,
    })
}

pub async fn heartbeat(
    installed: &InstalledState,
    scope: &IngestScope,
    facts: DeviceFactsInput,
) -> Result<(), AppError> {
    facts
        .validate()
        .map_err(|message| AppError::Validation(message.into()))?;
    let received_at = chrono::Utc::now().timestamp_millis();
    let observation = DeviceObservation {
        kind: DeviceTelemetryKind::Heartbeat,
        received_at,
        telemetry_at: received_at,
        item_count: 0,
        session_id: None,
        app_version: timed_fact(facts.app_version, received_at),
        launcher_version: timed_fact(facts.launcher_version, received_at),
        os: timed_fact(facts.os, received_at),
        system_language: timed_fact(facts.system_language, received_at),
        architecture: timed_fact(facts.architecture, received_at),
    };
    let storage_scope = scope.storage_scope();
    let device_hash = device_hash_for_scope(scope);
    device_state::observe(
        &installed.database,
        &storage_scope,
        &device_hash,
        &observation,
    )
    .await?;
    Ok(())
}

pub async fn events(
    installed: &InstalledState,
    scope: &IngestScope,
    mut items: Vec<EventInput>,
) -> Result<BatchReceipt, AppError> {
    ensure_batch_size(items.len())?;
    charge_item_budget(installed, scope, items.len()).await?;
    let (accepted, rejected) = validate_with(&mut items, |item| normalize_live_event(scope, item));
    let mut valid = select_valid(items, &rejected);
    let observation = event_observation(&valid);
    for item in &mut valid {
        item.anonymous_id = item.anonymous_id.take().map(|id| {
            device_identity::scoped_hash_parts(&scope.application_id, &scope.environment_id, &id)
        });
    }
    let storage_scope = scope.storage_scope();
    installed
        .ingest_writer
        .write_events(&storage_scope, valid)
        .await?;
    observe_signed_device(installed, scope, &storage_scope, observation).await;
    Ok(BatchReceipt { accepted, rejected })
}

