fn timed_fact(value: Option<String>, received_at: i64) -> Option<TimedDimension> {
    value.map(|value| TimedDimension {
        value,
        timestamp: received_at,
    })
}

fn update_current_dimension(
    target: &mut Option<TimedDimension>,
    value: Option<&str>,
    received_at: i64,
) {
    let Some(value) = value else {
        return;
    };
    *target = Some(TimedDimension {
        value: value.to_owned(),
        timestamp: received_at,
    });
}

fn device_hash_for_scope(scope: &IngestScope) -> String {
    device_identity::scoped_hash_parts(
        &scope.application_id,
        &scope.environment_id,
        scope.signed_device_id(),
    )
}

async fn charge_item_budget(
    installed: &InstalledState,
    scope: &IngestScope,
    item_count: usize,
) -> Result<(), AppError> {
    if !installed
        .auth_security
        .ingest
        .check_ip_ingest_items(&scope.source_ip, item_count)
        .await
    {
        return Err(AppError::TooManyRequests);
    }
    let policy = ingest_abuse::policy_for_tier(scope.risk_tier);
    if !installed
        .auth_security
        .ingest
        .check_device_ingest_items(
            &scope.application_id,
            &scope.device_id,
            ingest_abuse::scaled_cost(item_count, policy.item_cost_multiplier),
        )
        .await
    {
        return Err(AppError::TooManyRequests);
    }
    Ok(())
}

async fn charge_device_token_budget(
    installed: &InstalledState,
    application_id: &str,
    device_id: &str,
    multiplier: u64,
) -> Result<bool, AppError> {
    Ok(ingest_bootstrap::charge_device_token(
        &installed.database,
        installed.auth_security.pepper(),
        application_id,
        device_id,
        multiplier,
    )
    .await?)
}

async fn charge_device_request_budget(
    installed: &InstalledState,
    application_id: &str,
    device_id: &str,
    multiplier: u64,
) -> bool {
    for _ in 0..std::cmp::max(multiplier, 1) {
        if !installed
            .auth_security
            .ingest
            .check_device_rate(application_id, device_id)
            .await
        {
            return false;
        }
    }
    true
}

fn ensure_batch_size(length: usize) -> Result<(), AppError> {
    if length > MAX_BATCH_ITEMS {
        return Err(AppError::Validation(format!(
            "maximum batch size is {MAX_BATCH_ITEMS}"
        )));
    }
    Ok(())
}

fn validate_with<T: ValidateTelemetry>(
    items: &mut [T],
    mut normalize: impl FnMut(&mut T) -> Result<(), &'static str>,
) -> (usize, Vec<RejectedItem>) {
    let mut accepted = 0;
    let mut rejected = Vec::new();
    for (index, item) in items.iter_mut().enumerate() {
        let result = normalize(item).and_then(|()| item.validate());
        if let Err(reason) = result {
            rejected.push(RejectedItem { index, reason });
        } else {
            accepted += 1;
        }
    }
    (accepted, rejected)
}

fn normalize_live_event(scope: &IngestScope, item: &mut EventInput) -> Result<(), &'static str> {
    reject_server_owned_live_fields(
        item.timestamp,
        item.session_id.as_deref(),
        item.anonymous_id.as_deref(),
    )?;
    item.anonymous_id = Some(scope.device_id.clone());
    Ok(())
}

fn normalize_live_error(scope: &IngestScope, item: &mut ErrorInput) -> Result<(), &'static str> {
    reject_server_owned_live_fields(
        item.timestamp,
        item.session_id.as_deref(),
        item.anonymous_id.as_deref(),
    )?;
    item.anonymous_id = Some(scope.device_id.clone());
    Ok(())
}

fn reject_server_owned_live_fields(
    timestamp: Option<i64>,
    session_id: Option<&str>,
    anonymous_id: Option<&str>,
) -> Result<(), &'static str> {
    if timestamp.is_some() {
        return Err("timestamp is server-owned for live ingest");
    }
    if session_id.is_some() {
        return Err("sessionId is server-owned for live ingest");
    }
    if anonymous_id.is_some() {
        return Err("anonymousId is derived from the signed device token for live ingest");
    }
    Ok(())
}

fn reject_live_timestamp<T: LiveTimestamp>(item: &mut T) -> Result<(), &'static str> {
    if item.live_timestamp().is_some() {
        return Err("timestamp is server-owned for live ingest");
    }
    Ok(())
}

trait LiveTimestamp {
    fn live_timestamp(&self) -> Option<i64>;
}

impl LiveTimestamp for MetricInput {
    fn live_timestamp(&self) -> Option<i64> {
        self.timestamp
    }
}

impl LiveTimestamp for LogInput {
    fn live_timestamp(&self) -> Option<i64> {
        self.timestamp
    }
}

fn select_valid<T>(items: Vec<T>, rejected: &[RejectedItem]) -> Vec<T> {
    if rejected.is_empty() {
        return items;
    }
    let rejected_indices: std::collections::HashSet<_> =
        rejected.iter().map(|item| item.index).collect();
    items
        .into_iter()
        .enumerate()
        .filter_map(|(index, item)| {
            if rejected_indices.contains(&index) {
                None
            } else {
                Some(item)
            }
        })
        .collect()
}

fn validate_user_agent(value: &str) -> Result<&str, AppError> {
    let value = value.trim();
    if value.is_empty()
        || value.len() > 512
        || value.chars().any(|character| character.is_control())
    {
        return Err(AppError::Validation(
            "User-Agent must be 1..512 visible bytes".into(),
        ));
    }
    Ok(value)
}

fn validate_device_id(value: &str) -> Result<&str, AppError> {
    let value = value.trim();
    if value.len() < 4
        || value.len() > 128
        || !value.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.' | ':')
        })
    {
        return Err(AppError::Validation(
            "deviceId must be 4..128 bytes using letters, digits, '-', '_', '.', or ':'".into(),
        ));
    }
    Ok(value)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::{IngestScope, event_observation, normalize_live_event, simple_observation};
    use crate::{
        database::device_state::DeviceTelemetryKind, domain::telemetry::EventInput,
        services::ingest_abuse::RiskTier,
    };

    fn scope() -> IngestScope {
        IngestScope {
            application_id: "app".into(),
            environment_id: "env".into(),
            source_ip: "127.0.0.1".into(),
            device_id: "device-1234".into(),
            risk_tier: RiskTier::Low,
        }
    }

    fn event() -> EventInput {
        EventInput {
            name: "startup".into(),
            timestamp: None,
            anonymous_id: None,
            session_id: None,
            app_version: Some("2.0.0".into()),
            launcher_version: Some("1.5.0".into()),
            os: Some("windows".into()),
            system_language: None,
            architecture: None,
            idempotency_key: None,
            attributes: Default::default(),
        }
    }

    #[test]
    fn live_ingest_rejects_client_owned_identity_and_time_fields() {
        let scope = scope();

        let mut with_timestamp = event();
        with_timestamp.timestamp = Some(100);
        assert!(normalize_live_event(&scope, &mut with_timestamp).is_err());

        let mut with_session = event();
        with_session.session_id = Some("client-session".into());
        assert!(normalize_live_event(&scope, &mut with_session).is_err());

        let mut with_identity = event();
        with_identity.anonymous_id = Some("device-1234".into());
        assert!(normalize_live_event(&scope, &mut with_identity).is_err());
    }

    #[test]
    fn live_ingest_injects_identity_from_signed_token() {
        let scope = scope();
        let mut event = event();
        assert!(normalize_live_event(&scope, &mut event).is_ok());
        assert_eq!(event.anonymous_id.as_deref(), Some("device-1234"));
        assert!(event.timestamp.is_none());
        assert!(event.session_id.is_none());
        assert_eq!(event.app_version.as_deref(), Some("2.0.0"));
        assert_eq!(event.launcher_version.as_deref(), Some("1.5.0"));
        assert_eq!(event.os.as_deref(), Some("windows"));
    }

    #[test]
    fn platform_selects_current_dimensions_at_server_receive_time() {
        let mut first = event();
        first.app_version = Some("1.0.0".into());
        let mut second = event();
        second.app_version = Some("2.0.0".into());
        second.os = Some("linux".into());
        let observation = event_observation(&[first, second]).unwrap();
        assert_eq!(
            observation
                .app_version
                .as_ref()
                .map(|value| value.value.as_str()),
            Some("2.0.0")
        );
        assert_eq!(
            observation.os.as_ref().map(|value| value.value.as_str()),
            Some("linux")
        );
        assert_eq!(observation.telemetry_at, observation.received_at);
        assert!(observation.session_id.is_none());
    }

    #[test]
    fn metrics_and_logs_advance_server_owned_device_activity() {
        let observation = simple_observation(DeviceTelemetryKind::Metric, 2).unwrap();
        assert_eq!(observation.telemetry_at, observation.received_at);
        assert!(observation.session_id.is_none());
        assert!(observation.app_version.is_none());
    }
}
